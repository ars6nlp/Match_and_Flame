def rgba(c, a=255):
    return tuple(c[:3]) + (a,)


class Cell:
    """Ячейка листа: рисуем в увеличенном холсте, потом уменьшаем."""

    def __init__(self, w, h):
        self.w, self.h = w, h
        self.img = Image.new("RGBA", (w * SS, h * SS), (0, 0, 0, 0))
        self.d = ImageDraw.Draw(self.img)

    def p(self, x, y):
        return (x * self.w * SS, y * self.h * SS)

    def box(self, x0, y0, x1, y1):
        return [x0 * self.w * SS, y0 * self.h * SS, x1 * self.w * SS, y1 * self.h * SS]

    def lw(self, v):
        return max(1, int(v * self.w * SS))

    def shape(self, kind, coords, top, bottom=None, outline=INK, width=0.025, radius=0.0, shade=True):
        """Заливка вертикальным градиентом top→bottom по маске фигуры, затем обводка."""
        bottom = bottom or top
        mask = Image.new("L", self.img.size, 0)
        md = ImageDraw.Draw(mask)
        self._draw(md, kind, coords, fill=255, radius=radius)
        ys = [c[1] for c in coords] if kind == "poly" else [coords[1], coords[3]]
        y0, y1 = min(ys), max(ys)
        grad = Image.new("RGBA", self.img.size)
        gd = ImageDraw.Draw(grad)
        h = max(1, int(y1 - y0))
        for i in range(h + 1):
            t = i / h
            c = tuple(int(top[k] * (1 - t) + bottom[k] * t) for k in range(3)) + (255,)
            gd.line([(0, y0 + i), (self.img.size[0], y0 + i)], fill=c)
        if y0 > 0:
            gd.rectangle([0, 0, self.img.size[0], y0], fill=rgba(top))
        if y1 < self.img.size[1]:
            gd.rectangle([0, y1, self.img.size[0], self.img.size[1]], fill=rgba(bottom))
        self.img.paste(grad, (0, 0), mask)
        if outline and width > 0:
            self._draw(self.d, kind, coords, outline=outline, width=self.lw(width), radius=radius)

    def _draw(self, d, kind, coords, fill=None, outline=None, width=0, radius=0.0):
        if kind == "rect":
            if radius > 0:
                d.rounded_rectangle(coords, radius=radius * self.w * SS, fill=fill, outline=outline, width=width)
            else:
                d.rectangle(coords, fill=fill, outline=outline, width=width)
        elif kind == "ellipse":
            d.ellipse(coords, fill=fill, outline=outline, width=width)
        elif kind == "poly":
            if fill is not None:
                d.polygon(coords, fill=fill)
            if outline is not None:
                d.line(coords + [coords[0]], fill=outline, width=width, joint="curve")

    # удобные обёртки в долях ячейки
    def rect(self, x0, y0, x1, y1, top, bottom=None, r=0.0, w=0.025, outline=INK):
        self.shape("rect", self.box(x0, y0, x1, y1), top, bottom, outline, w, r)

    def ell(self, x0, y0, x1, y1, top, bottom=None, w=0.025, outline=INK):
        self.shape("ellipse", self.box(x0, y0, x1, y1), top, bottom, outline, w)

    def poly(self, pts, top, bottom=None, w=0.025, outline=INK):
        self.shape("poly", [self.p(x, y) for x, y in pts], top, bottom, outline, w)

    def line(self, pts, color=INK, w=0.025):
        self.d.line([self.p(x, y) for x, y in pts], fill=rgba(color), width=self.lw(w), joint="curve")

    def dot(self, x, y, r, color, outline=None, w=0.0):
        self.d.ellipse(self.box(x - r, y - r, x + r, y + r), fill=rgba(color), outline=outline, width=self.lw(w) if w else 0)

    def glow(self, x, y, r, color, alpha=150):
        # Радиальное свечение, гаснущее к нулю внутри радиуса (без квадратного края у ячейки)
        import numpy as np
        W, H = self.img.size
        yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
        cx, cy, rr = x * W, y * H, r * self.w * SS
        d = np.sqrt((xx - cx) ** 2 + (yy - cy) ** 2) / max(1.0, rr)
        a = (np.clip(1.0 - d, 0, 1) ** 2 * alpha).astype(np.uint8)
        g = np.zeros((H, W, 4), np.uint8)
        g[..., 0], g[..., 1], g[..., 2], g[..., 3] = color[0], color[1], color[2], a
        self.img.alpha_composite(Image.fromarray(g, "RGBA"))

    def highlight(self, x0, y0, x1, y1, alpha=70):
        g = Image.new("RGBA", self.img.size, (0, 0, 0, 0))
        ImageDraw.Draw(g).ellipse(self.box(x0, y0, x1, y1), fill=(255, 255, 255, alpha))
        g = g.filter(ImageFilter.GaussianBlur(self.w * SS * 0.02))
        self.img.alpha_composite(g)

    def result(self):
        return self.img.resize((self.w, self.h), Image.LANCZOS)


def flame_shape(c, cx, cy, s, top=(255, 236, 150), bottom=(255, 120, 40), w=0.02):
    pts = []
    for i in range(41):
        a = math.pi * 2 * i / 40
        r = s * (0.55 + 0.45 * max(0, -math.sin(a)) ** 0.5)
        x = cx + math.cos(a) * s * 0.62
        y = cy + math.sin(a) * s * 0.75
        if math.sin(a) < 0:
            y = cy - s * (1.0 - (math.cos(a) ** 2) * 0.7) * 1.1
            x = cx + math.cos(a) * s * 0.55 * (1 - 0.4 * (-math.sin(a)))
        pts.append((x, y))
    c.poly(pts, top, bottom, w)


